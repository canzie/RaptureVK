#!/usr/bin/env python3
"""Writes icons.js, the editor's SVG icons from Editor/src/Icons.h, for the HTML mocks."""

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ICONS_HEADER = os.path.join(HERE, "..", "..", "Editor", "src", "Icons.h")

ICON_PREFIX = ('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" fill="none" stroke="currentColor" '
               'stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round">')


def readLiterals(source):
    """Concatenates every C string literal in a piece of source, undoing its escapes."""
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', source)
    return "".join(bytes(part, "utf-8").decode("unicode_escape") for part in parts)


def main():
    header = open(ICONS_HEADER).read()
    icons = {}
    for match in re.finditer(r"SVG_(\w+)\s*=\s*(.*?);", header, re.S):
        name, body = match.group(1), match.group(2)
        if not body.lstrip().startswith("ICON_SVG("):
            continue
        svg = ICON_PREFIX + readLiterals(body) + "</svg>"
        icons[name] = svg.replace("#ffffff", "currentColor")

    with open(os.path.join(HERE, "icons.js"), "w") as out:
        out.write("// generated by extract_icons.py from Editor/src/Icons.h\n")
        out.write("const ICONS = " + json.dumps(icons, indent=1) + ";\n")
    print("%d icons" % len(icons))


if __name__ == "__main__":
    main()
